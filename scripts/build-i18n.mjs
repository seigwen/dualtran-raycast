#!/usr/bin/env node
/**
 * build-i18n.mjs — bundle every locale catalogue into src/i18n.generated.ts,
 * which the Raycast build inlines.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = path.join(ROOT, "locales");
const OUT = path.join(ROOT, "src", "i18n.generated.ts");

const locales = {};
for (const entry of fs.readdirSync(LOCALES, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(LOCALES, entry.name, "messages.json");
  if (fs.existsSync(file)) locales[entry.name] = JSON.parse(fs.readFileSync(file, "utf8"));
}

const body = [
  "/* Generated by scripts/build-i18n.mjs — do not edit. */",
  "export type LocaleCatalogue = Record<string, { message: string }>;",
  `export const LOCALES: Record<string, LocaleCatalogue> = ${JSON.stringify(locales, null, 2)};`,
  "",
].join("\n");

fs.writeFileSync(OUT, body);
console.log(`[build-i18n] ${Object.keys(locales).length} locales → src/i18n.generated.ts`);

// Keep the generated file in the shape `ray lint` (Prettier) accepts.
try {
  const { execFileSync } = await import("node:child_process");
  execFileSync(path.join(ROOT, "node_modules", ".bin", "prettier"), ["--write", OUT], { stdio: "ignore" });
} catch {
  /* prettier is optional at build time */
}
